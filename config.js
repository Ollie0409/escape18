/* Escape 18 site settings + platform lesson bridge. Every lesson loads this as ../config.js BEFORE its engine (lesson HTML stays
   unchanged). endpoint: the Google Apps Script web app URL for anonymous results; contact: e-mail address shown on the site.
   Outside the platform pupil shell (top level, an LMS iframe, any cross-origin or non-shell parent) it is exactly the repo
   config.js: window.E18_CONFIG = { endpoint, contact } and nothing else.
   Inside the shell (same-origin parent with window.E18P_SHELL === true): the engine's results endpoint becomes a sentinel, and
   every batch the engine posts to it is handed to the parent window as {e18p:'events', batch} instead of going to the network.
   With &r=1 in the lesson URL (teacher ticked research logging) the endpoint is the research URL: the batch goes to the parent
   AND to the network as before. The sentinel must sit on script.google.com: both engines only log to an endpoint on the Google
   Apps Script origins. It is never requested: sendBeacon/fetch to it are answered here. Generated by tools/build.mjs. */
(function () {
  'use strict';
  var RESEARCH = "https://script.google.com/macros/s/AKfycbxSxoV_mnLENuquB2RGu6px43ZQEJlyOMVR4aRqy1jpWkYm7PMKyoJhFdkMbFN3h8A4/exec";
  var CONTACT = "olivierrunge@gmail.com";
  var SENTINEL = 'https://script.google.com/macros/s/e18p-platform-relay/exec';
  var shell = false;
  try {
    var par = window.parent;
    shell = par != null && par !== window && par.location.origin === window.location.origin && par.E18P_SHELL === true;
  } catch (e) { shell = false; } // cross-origin parent: reading it throws
  if (!shell) { window.E18_CONFIG = { endpoint: RESEARCH, contact: CONTACT }; return; }
  var research = /[?&]r=1(?:&|$)/.test(location.search);
  var endpoint = research ? RESEARCH : SENTINEL;
  window.E18_CONFIG = { endpoint: endpoint, contact: CONTACT };
  window.E18P_BRIDGE = { sentinel: SENTINEL, research: research };
  var nav = window.navigator;
  function same(url) { try { return String(url && url.url ? url.url : url).trim() === endpoint; } catch (e) { return false; } }
  function forward(text) {
    var batch;
    try { batch = JSON.parse(text); } catch (e) { return; }
    if (!Array.isArray(batch)) batch = [batch];
    try { window.parent.postMessage({ e18p: 'events', batch: batch }, location.origin); } catch (e) { /* parent gone */ }
  }
  function readBody(body) {
    if (body == null) return;
    if (typeof body === 'string') { forward(body); return; }
    if (typeof body.text === 'function') { body.text().then(forward, function () {}); return; }
    try { forward(String(body)); } catch (e) { /* unknown body type */ }
  }
  var origBeacon = nav && nav.sendBeacon;
  if (typeof origBeacon === 'function') {
    nav.sendBeacon = function (url, data) {
      if (!same(url)) return origBeacon.apply(nav, arguments);
      readBody(data);
      if (!research) return true;
      return origBeacon.apply(nav, arguments);
    };
  }
  var origFetch = window.fetch;
  if (typeof origFetch === 'function') {
    window.fetch = function (input, init) {
      if (!same(input) || !init || String(init.method || 'GET').toUpperCase() !== 'POST') return origFetch.apply(window, arguments);
      readBody(init.body);
      if (!research) { try { return Promise.resolve(new Response(null, { status: 204 })); } catch (e) { return Promise.resolve({ ok: true, status: 204 }); } }
      return origFetch.apply(window, arguments);
    };
  }
  if (!research) {
    // The pupil shell queues frames while offline, so the engine may keep handing batches over: report online to it.
    try { Object.defineProperty(nav, 'onLine', { configurable: true, get: function () { return true; } }); } catch (e) { /* read-only */ }
  }
  // The topic engine flushes every 15 s; ask it every 2 s so the teacher's live view stays close to real time.
  setInterval(function () { try { if (window.E18Log && typeof window.E18Log.flush === 'function') window.E18Log.flush(); } catch (e) { /* engine not ready */ } }, 2000);
})();
